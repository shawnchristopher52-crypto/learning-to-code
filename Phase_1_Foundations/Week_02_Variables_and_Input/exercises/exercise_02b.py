# integer
print(type(7))

# float
print(type(7.0))

# string
print(type("7"))

# Boolean
print(type(True))

# String
print(type("True"))

# Integer
print(type(7 + 0))

# Float
print(type(7 + 0.0))

# String
print(type("7" + "0"))

# Bonus: The difference between True and "True" is that True / False are boolean but when the quotes are around the value
# python treats it as an exact value for str.